"""
CoderConnector, registered under tool name "coder".

This is the runnable slice of the paper's "code-centric Executors" idea
(Section 4.2: "Qwen2.5-Coder-32B-Instruct and DeepSeek-Coder-V2 ... serve
code-centric Executors such as the SWE-agent module and formula or SQL
generation"). The full SWE-agent module (Docker-sandboxed repository
maintenance, Section 6) is explicitly future work in the paper and is not
implemented here; this connector covers the other half of that sentence -
letting a task ask for a short piece of SQL, a spreadsheet formula, or a
small code snippet, generated by the gateway's "coder" role.

Like every other connector, it never fails the run with zero setup: if no
local coder model is reachable (src/llm/gateway.py raises
LLMUnavailableError), it returns a clearly-marked TODO stub instead of
raising, the same "runs with nothing configured" contract the rest of the
project follows.
"""
from __future__ import annotations

from typing import Any, Dict, Optional

from src.llm.client import LLMUnavailableError
from src.llm.gateway import ModelGateway
from src.tools.base_tool import BaseTool, ToolSchema

CODER_SYSTEM_PROMPT = """You are the Coder role of an agentic workflow \
automation system. You generate a single short, correct snippet - SQL, a \
spreadsheet formula, or a small code function - for exactly the \
instruction given. Respond with ONLY the code/formula, no prose, no \
markdown fences, no explanation."""


class CoderConnector(BaseTool):
    name = "coder"
    schema = ToolSchema(
        input_fields=["instruction", "language"],
        output_fields=["code", "language", "generated_by"],
    )

    def __init__(self, gateway: Optional[ModelGateway] = None):
        self.gateway = gateway or ModelGateway(role="coder")

    def run(self, args: Dict[str, Any]) -> Dict[str, Any]:
        instruction = (args.get("instruction") or "").strip()
        language = args.get("language") or "sql"
        if not instruction:
            raise ValueError("CoderConnector requires a non-empty 'instruction'.")

        try:
            response = self.gateway.generate(
                role="coder",
                system=CODER_SYSTEM_PROMPT,
                user=f"Language: {language}\nInstruction: {instruction}",
            )
            return {
                "code": response.text.strip(),
                "language": language,
                "generated_by": (response.raw or {}).get("model", "coder"),
            }
        except LLMUnavailableError:
            # Deterministic fallback so the pipeline still runs end-to-end
            # with no Ollama/vLLM server up - mirrors PlannerAgent's
            # keyword fallback rather than failing the task outright.
            return {
                "code": f"-- TODO ({language}): {instruction}\n"
                f"-- No local coder model reachable; run Ollama/vLLM and "
                f"pull the model(s) in config/llm_routing.yaml to fill this in.",
                "language": language,
                "generated_by": "fallback",
            }
